# ── Метрики совместимости (compatibility_metrics.py) ──────────────────────────
# Секция «Тепло» убрана из карточки целиком — вместе с ней не нужны и её
# словари (WARM_LEXICON / FEELING_VERBS / AMBIGUOUS_PRAISE_WORDS / WARM_EMOJI).
# Причина не в конкретных словах, а в методе: словарь не видит контекст, и
# совпадение стема засчитывалось теплом независимо от адресата — «обожаю этот
# фильм», «молодец, успел среагировать», «я обожаю её». Правки по границе
# слова, проверке направленности глаголов и LLM-подтверждению неоднозначной
# похвалы закрывали очередной частный случай, но не проблему.
# Вместо неё в карточке — детерминированная метрика «Кто чаще задаёт вопросы»
# (compatibility_metrics.question_balance). Словари оставлены закомментированными
# на случай возврата к теме уже не словарным методом.
# # WARM_LEXICON: стем → каноническое имя категории (для occurrence-подсчёта
# # топ-слов, см. compatibility_metrics.warmth). Матчинг — по границе слова
# # С ЛЕВОЙ стороны стема, не по вхождению подстроки: стемы — намеренно префиксы
# # словоформ («любим» должен матчить «любимая»/«любимый», поэтому \b только
# # слева, не с обеих сторон — иначе сломались бы все словоформы).
# #
# # ТОЛЬКО вокативные обращения — слова, которыми напрямую ЗОВУТ собеседника
# # («зая, привет»), направленность синтаксически гарантирована самим их
# # использованием, отдельно проверять НЕ нужно. Глаголы чувств (люблю/обожаю/
# # скучаю/целую/обнимаю и т.п.) сюда НЕ входят — см. FEELING_VERBS ниже: без
# # проверки «на кого направлено» они матчат что угодно («обожаю этот фильм»,
# # «я обожаю её» — про третье лицо, не про собеседника).
# WARM_LEXICON = {
#     "любим": "любимый", "любов": "любовь",
#     "детк": "детка", "зая": "зая", "зайк": "зайка", "зайч": "зайчик",
#     "солнц": "солнце", "родн": "родной", "котен": "котёнок", "котик": "котик",
#     "мур": "мур", "ласков": "ласковый", "дорог": "дорогой",
#     "милый": "милый", "миленьк": "миленький", "нежн": "нежность",
#     "сердц": "сердце", "ангел": "ангел", "счасть": "счастье",
#     "красотк": "красотка", "красив": "красивый",
# }
#
# # Глаголы чувств — В ОТЛИЧИЕ от вокативных обращений выше, могут быть
# # направлены на что угодно (фильм, работу, третье лицо, себя самого), а не
# # только на собеседника. compatibility_metrics.warmth проверяет
# # направленность для каждого совпадения отдельно (рядом «тебя»/«тебе»/
# # «тобой» → тепло; рядом «её»/«его»/«их» → явно не про собеседника, не
# # считается; иначе — неопределённость, кандидат на ту же LLM-проверку, что
# # и AMBIGUOUS_PRAISE_WORDS ниже).
# FEELING_VERBS = {
#     "люблю": "люблю", "обожаю": "обожаю",
#     "скучаю": "скучаю", "скучаешь": "скучаешь",
#     "целую": "целую", "поцелу": "поцелуй",
#     "обнимаю": "обнимаю", "обним": "обнимашки",
#     "влюб": "влюблён",
# }
#
# # Слишком общие слова похвалы — ими хвалят что угодно, не только романтически
# # («молодец, быстро починил» — не про отношения). Матчатся тем же
# # word-boundary механизмом, что WARM_LEXICON, но НЕ засчитываются сразу —
# # кандидаты идут на LLM-проверку (см. compatibility_metrics.
# # find_ambiguous_warmth_candidates + llm.classify_ambiguous_praise).
# AMBIGUOUS_PRAISE_WORDS = {
#     "молодец": "молодец", "умниц": "умница", "умничк": "умничка",
#     "молодчин": "молодчина",
# }
#
# # Точное совпадение символа (НЕ regex по подстроке текста) — сообщение с таким
# # эмодзи тоже безусловно тёплое.
# WARM_EMOJI = {"❤️", "🥰", "😘", "🥺", "💕", "💞", "💓", "💗", "💖", "💘", "😍", "🫶"}
